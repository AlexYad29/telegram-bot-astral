"""Нумерологические расчёты.

Реализован Pythagorean-метод, расширенный таблицей значений для кириллицы.
Алгоритм буквенного значения — позиция в алфавите по модулю 9 (с переносом 0→9),
что совпадает с классической пифагорейской матрицей.

Сохраняем мастер-числа `11/22/33` — их не сворачиваем.

Никаких зависимостей от aiogram / БД — чистые функции, удобно тестировать.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

#: Латинская пифагорейская таблица: A=1, B=2, …, I=9, J=1, …
_LATIN_LETTERS: str = "abcdefghijklmnopqrstuvwxyz"

#: Полный кириллический алфавит (33 буквы). Ё пишем отдельно от Е.
_CYRILLIC_LETTERS: str = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"


def _build_letter_values(alphabet: str) -> dict[str, int]:
    """Сгенерировать таблицу значений: позиция (1-based) по модулю 9 (0 → 9)."""
    table: dict[str, int] = {}
    for idx, letter in enumerate(alphabet, start=1):
        value = idx % 9
        table[letter] = value if value != 0 else 9
    return table


_LATIN_VALUES: dict[str, int] = _build_letter_values(_LATIN_LETTERS)
_CYRILLIC_VALUES: dict[str, int] = _build_letter_values(_CYRILLIC_LETTERS)

#: Мастер-числа, которые сохраняем без редукции.
MASTER_NUMBERS: frozenset[int] = frozenset({11, 22, 33})


def _reduce(n: int) -> int:
    """Свернуть число до одной цифры, сохранив мастер-числа 11/22/33.

    >>> _reduce(29)
    2
    >>> _reduce(11)
    11
    >>> _reduce(38)
    2
    """
    if n < 0:
        raise ValueError("ожидалось неотрицательное число")
    while n > 9 and n not in MASTER_NUMBERS:
        n = sum(int(d) for d in str(n))
    return n


def _letter_value(ch: str) -> int | None:
    """Вернуть числовое значение буквы или `None`, если символ не учитывается."""
    lower = ch.lower()
    if lower in _LATIN_VALUES:
        return _LATIN_VALUES[lower]
    # Унифицируем `ё`/`е`-кейсы — ё считаем отдельной буквой (значение 7).
    if lower in _CYRILLIC_VALUES:
        return _CYRILLIC_VALUES[lower]
    return None


def life_path_number(birth_date: date) -> int:
    """Число судьбы (Life Path).

    Суммируем все цифры даты `YYYY-MM-DD`, сворачиваем до одной цифры либо
    одного из мастер-чисел.
    """
    digits_sum = sum(int(ch) for ch in birth_date.strftime("%Y%m%d"))
    return _reduce(digits_sum)


def expression_number(full_name: str) -> int:
    """Число личности / выражения (Expression).

    Суммируем значения всех букв (латиница + кириллица), пропускаем пробелы,
    цифры и знаки препинания. Если в имени нет ни одной значимой буквы —
    `ValueError`.
    """
    total = 0
    counted = 0
    for ch in full_name:
        value = _letter_value(ch)
        if value is not None:
            total += value
            counted += 1
    if counted == 0:
        raise ValueError("имя не содержит букв, для расчёта недостаточно данных")
    return _reduce(total)


